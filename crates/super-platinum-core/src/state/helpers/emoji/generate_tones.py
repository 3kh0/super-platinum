"""Generate exact static display lookup from the retained standard catalogs.

Run with --check for reproducibility. No runtime catalog loading is introduced.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[2] / "composer_emoji"


def catalog(version):
    path = SOURCE / f"slack-emoji-v{version}-ordered.json"
    data = path.read_bytes()
    rows = json.loads(data)
    result = {}
    for row in rows:
        variants = []
        for tone, variant in sorted(row.get("skinVariations", {}).items()):
            assert re.fullmatch(r"[2-6](?:-[2-6])?", tone)
            assert variant["name"] == row["name"] + "::skin-tone-" + tone
            points = [int(p, 16) for p in variant["unicode"].split("-")]
            assert points and all(0 <= p <= 0x10FFFF and not 0xD800 <= p <= 0xDFFF for p in points)
            glyph = '"' + "".join(r"\u{" + format(p, "x") + "}" for p in points) + '"'
            variants.append((tone, glyph))
        if variants:
            assert row["name"] not in result
            result[row["name"]] = tuple(variants)
    return result, hashlib.sha256(data).hexdigest()


def generate():
    old, old_hash = catalog(16)
    current, current_hash = catalog(17)
    for name, variants in old.items():
        assert set(variants) <= set(current[name]), name
    groups = []
    bases = []
    for name, variants in sorted(current.items()):
        if variants not in groups:
            groups.append(variants)
        bases.append((name, groups.index(variants)))
    lines = [
        "// Generated by generate_tones.py; do not edit.",
        f"// Retained V16 SHA256 {old_hash}",
        f"// Retained V17 SHA256 {current_hash}",
        f"// {len(bases)} exact bases, {sum(map(len, current.values()))} variants, {len(groups)} shared tables.",
        "#[rustfmt::skip]",
        "pub(super) static BASES: &[(&str, usize)] = &[",
        *[f"    ({json.dumps(name)}, {index})," for name, index in bases],
        "];",
        "#[rustfmt::skip]",
        "pub(super) static GROUPS: &[&[(&str, &str)]] = &[",
        *["    &[" + ", ".join(f'("{tone}", {glyph})' for tone, glyph in group) + "]," for group in groups],
        "];",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = HERE / "tones_data.rs"
    content = generate()
    if args.check:
        assert path.read_text(encoding="utf-8") == content, "Static tone lookup is stale"
    else:
        path.write_text(content, encoding="utf-8", newline="\n")
    print(json.dumps({"check": args.check, "sha256": hashlib.sha256(content.encode()).hexdigest()}))
