import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root = process.argv[2];
assert.ok(root, 'candidate root required');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const media = read('src/desktop/media.rs');
const narrow = media.slice(media.indexOf('let initial_size ='), media.indexOf('let initial_size =') + 22000);
assert.ok(narrow.includes('"slack-list-field-delete-narrow"'));
assert.equal((media.match(/"slack-list-field-delete-narrow"/g) || []).length, 1);
assert.equal((media.match(/"slack-list-field-delete"/g) || []).length, 0);
console.log('PASS normal alias never enters narrow size branch');
const boot = read('src/desktop/state/boot.rs');
assert.match(boot, /"slack-list-field-delete" \| "slack-list-field-delete-narrow" => \{\s*crate::slack_lists::fixture::field_delete::install\(&mut state, name\);\s*\}/);
console.log('PASS both aliases use exact fixture installer');
const checker = read('src/desktop/slack_lists/check.rs');
assert.equal((checker.match(/field_delete::start\(state, desktop.clone\(\)\)/g)||[]).length,1);
assert.match(checker,/mod field_delete;/);
assert.match(read('src/desktop/slack_lists/fixture.rs'),/pub\(crate\) mod field_delete;/);
console.log('PASS checker and fixture are connected to existing startup');
const script = read('scripts/agent-ui-check.sh');
assert.match(script,/slack-list-field-delete slack-list-field-delete-narrow/);
assert.match(script,/slack-list-field-delete\|slack-list-field-delete-narrow\)\s*owned_route="Use the sealed field deletion runner/);
console.log('PASS named fixtures require owned capture route');
