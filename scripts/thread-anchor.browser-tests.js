window.runThreadAnchorTests = async (attach) => {
  const results = [];
  const assert = (ok, message) => { if (!ok) throw Error(message); };
  const settle = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  document.body.innerHTML = '<style>section{height:260px;width:450px;overflow:auto;overflow-anchor:none}.row{height:70px}</style><section id="message-timeline" data-timeline-scope="channel"></section><section id="thread-body" data-timeline-scope="thread"></section>';
  const channel = document.getElementById('message-timeline');
  const thread = document.getElementById('thread-body');
  const row = id => {const e=document.createElement('div');e.className='row';e.dataset.rowId=id;e.textContent=id;return e;};
  channel.append(...Array.from({length:20},(_,i)=>row(`r${i}`)));
  thread.append(...Array.from({length:12},(_,i)=>row(`r${i+4}`)));
  attach('message-timeline','superPlatinumTimelineAnchor');
  attach('thread-body','superPlatinumThreadAnchor');
  channel.scrollTop=350;thread.scrollTop=200;await settle();
  const target=thread.querySelector('[data-row-id="r7"]');
  const offset=()=>target.getBoundingClientRect().top-thread.getBoundingClientRect().top;
  const initial=offset();const channelTop=channel.scrollTop;
  window.superPlatinumThreadAnchor.hold();
  thread.prepend(...Array.from({length:4},(_,i)=>row(`r${i}`)));await settle();
  assert(Math.abs(offset()-initial)<1,'earlier page shifted thread reading position');
  assert(channel.scrollTop===channelTop,'thread pagination scrolled channel');
  results.push('earlier replies retain the visible row and leave channel untouched');
  thread.querySelector('[data-row-id="r5"]').style.height='240px';await settle();
  assert(Math.abs(offset()-initial)<1,'thread image resize moved selected row');
  results.push('thread media resizing preserves the reading position');
  window.superPlatinumThreadAnchor.hold();thread.append(row('r16'),row('r17'));await settle();
  assert(Math.abs(offset()-initial)<1,'newer page moved history reader');
  results.push('newer reply page does not pull a history reader down');
  thread.dispatchEvent(new WheelEvent("wheel",{deltaY:900,bubbles:true}));thread.scrollTop=thread.scrollHeight;await settle();
  window.superPlatinumThreadAnchor.hold();const previousTop=thread.scrollTop;
  thread.append(row('r18'),row('r19'));await settle();
  assert(Math.abs(thread.scrollTop-previousTop)<1,'manual pagination followed the new bottom');
  results.push('explicit paging at the bottom retains the previous page');
  thread.dispatchEvent(new WheelEvent("wheel",{deltaY:900,bubbles:true}));thread.scrollTop=thread.scrollHeight;await settle();thread.append(row('r20'));await settle();
  assert(thread.scrollHeight-thread.scrollTop-thread.clientHeight<1,'normal thread arrival did not follow bottom');
  results.push('ordinary new replies still follow the bottom');
  thread.remove();window.superPlatinumThreadAnchor.check();
  const before=channel.scrollTop;channel.querySelector('[data-row-id="r1"]').style.height='200px';await settle();
  assert(channel.scrollTop>before,'closing thread disposed channel anchor');
  results.push('closing thread leaves channel anchoring alive');
  channel.remove();window.superPlatinumTimelineAnchor.check();
  return results;
};
